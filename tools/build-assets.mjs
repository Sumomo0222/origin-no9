// Build-time asset generation: webfonts export + world map SVG paths.
// Run: node tools/build-assets.mjs
import { mkdirSync, copyFileSync, readFileSync, writeFileSync } from "node:fs";
import * as topojson from "topojson-client";
import { geoNaturalEarth1, geoPath, geoGraticule10 } from "d3-geo";

const ROOT = new URL("..", import.meta.url).pathname;

// ---------- fonts ----------
function exportFont(pkg, weights, outDir, cssName) {
  const src = `${ROOT}node_modules/@fontsource/${pkg}`;
  const dst = `${ROOT}assets/fonts`;
  mkdirSync(dst, { recursive: true });
  const cssOut = [];
  for (const w of weights) {
    const css = readFileSync(`${src}/${w}.css`, "utf8");
    // keep only latin / chinese-simplified subsets actually used by @font-face blocks with woff2
    const blocks = css.split("@font-face").slice(1).map((b) => "@font-face" + b.split("}")[0] + "}");
    for (const block of blocks) {
      const srcMatch = block.match(/url\(\.\/files\/([^)]+\.woff2)\)/);
      if (!srcMatch) continue;
      const file = srcMatch[1];
      copyFileSync(`${src}/files/${file}`, `${dst}/${file}`);
      cssOut.push(block.replaceAll("./files/", "./"));
    }
  }
  writeFileSync(`${dst}/${cssName}.css`, cssOut.join("\n"));
  console.log(`fonts: ${cssName}.css (${cssOut.length} faces)`);
}

exportFont("marcellus", ["400"], "assets/fonts", "marcellus");
exportFont("noto-serif-sc", ["600", "700"], "assets/fonts", "noto-serif-sc");
exportFont("noto-sans-sc", ["400", "500"], "assets/fonts", "noto-sans-sc");

// ---------- world map ----------
const atlas = JSON.parse(readFileSync(`${ROOT}node_modules/world-atlas/countries-110m.json`, "utf8"));
const countries = topojson.feature(atlas, atlas.objects.countries);
// drop Antarctica (ISO 010) so the cacao belt fills the frame
countries.features = countries.features.filter((f) => f.id !== "010");

const W = 1000, H = 520;
const projection = geoNaturalEarth1().fitExtent(
  [[8, 8], [W - 8, H - 8]],
  { type: "FeatureCollection", features: countries.features }
);
const path = geoPath(projection);

const land = path(countries);
const borders = path(topojson.mesh(atlas, atlas.objects.countries, (a, b) => a !== b && a.id !== "010" && b.id !== "010"));
const grat = path(geoGraticule10());

// pre-projected marker anchors for the six fictional origins
const ORIGIN_COORDS = {
  ecuador: [-79.6, -1.6],
  peru: [-76.8, -7.2],
  ghana: [-1.6, 6.6],
  trinidad: [-61.35, 10.45],
  madagascar: [48.4, -13.6],
  vietnam: [106.3, 10.4],
};
const markers = Object.fromEntries(
  Object.entries(ORIGIN_COORDS).map(([k, c]) => {
    const [x, y] = projection(c);
    return [k, { x: +x.toFixed(1), y: +y.toFixed(1) }];
  })
);

const out = `// GENERATED by tools/build-assets.mjs — do not edit.
// Map geometry: Natural Earth via world-atlas (public domain), projected with d3-geo NaturalEarth1.
export const MAP = {
  width: ${W},
  height: ${H},
  land: ${JSON.stringify(land)},
  borders: ${JSON.stringify(borders)},
  graticule: ${JSON.stringify(grat)},
  markers: ${JSON.stringify(markers)},
};
`;
mkdirSync(`${ROOT}assets/js`, { recursive: true });
writeFileSync(`${ROOT}assets/js/map-data.js`, out);
console.log(`map: land ${(land.length / 1024).toFixed(0)}KB, markers ${JSON.stringify(markers)}`);
